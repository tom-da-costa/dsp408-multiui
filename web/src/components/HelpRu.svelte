<section id="help-start">
  <h2>Начало работы</h2>
  <p>
    Это приложение управляет одним DSP t.racks (408, 206 или 204) по сети. Его могут
    одновременно открыть все телефоны, планшеты и компьютеры в той же сети, введя код доступа.
    Все видят одни и те же настройки и индикаторы уровня в реальном времени.
  </p>
  <ul>
    <li>
      <strong>Изменения применяются сразу:</strong> движение регулятора сразу меняет звук.
      Ничего «отправлять» не нужно.
    </li>
    <li>
      <strong>Настройки хранятся в DSP.</strong> Чтобы сохранить конфигурацию после выключения
      DSP или загрузки другого пресета, запишите её в пресет (см. <em>Пресеты</em>).
    </li>
    <li>Подключение к интернету не требуется.</li>
  </ul>
</section>

