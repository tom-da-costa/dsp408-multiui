<section id="help-tabs">
  <h2>Вкладки</h2>
  <dl>
    <dt>🎛 Live</dt>
    <dd>
      Для работы во время концерта: по линейке на канал с крупными индикаторами CLIP / CMP /
      LIM, индикатором уровня (с отметками порогов компрессора <em>C</em> и лимитера
      <em>L</em> и белой линией пика), фейдером усиления и кнопкой MUTE. Нажмите на название
      канала, чтобы открыть его страницу.
    </dd>
    <dt>🎚 Params</dt>
    <dd>
      Одна настройка за раз на всех выбранных каналах: Gain, Delay, EQ, Filters, Comp, Limit,
      Gate, GEQ, Matrix и Link. Большинство показываются как линейки каналов рядом, чтобы
      сравнивать и настраивать их вместе. EQ показывает для каждого канала график частотной
      характеристики со списком полос; Matrix — сетка маршрутизации; Link объединяет каналы.
    </dd>
    <dt>🔈 Channels</dt>
    <dd>
      Всё об одном канале на одной странице: индикатор уровня с CLIP / CMP / LIM, частотная
      характеристика (с кривыми других каналов поверх, если выбрать их в <em>Compare with</em>)
      и все настройки. Канал выбирается в верхнем ряду.
    </dd>
    <dt>▥ All-in-one</dt>
    <dd>
      По столбцу на канал с настройками, выбранными в верхнем ряду, в порядке настройки системы:
      Name, Link, Matrix, Filters, Comp, Limit, Gain, EQ, Delay, затем Gate и GEQ (только входы,
      сначала скрыты). <strong>Mute</strong> находится под индикатором уровня каждого канала.
      Удобно на компьютере, чтобы видеть всю систему.
    </dd>
    <dt>🚨 Too loud</dt>
    <dd>
      Один большой индикатор для того, кто управляет громкостью. Он загорается, как только
      срабатывает хотя бы один компрессор или лимитер выхода, и показывает какие. Если иногда
      мигает — это нормально; если горит постоянно — убавьте громкость. Яркость настраивается
      внизу.
    </dd>
    <dt>🧮 Limiter calc</dt>
    <dd>
      Рассчитывает пороги компрессора и лимитера, защищающие ваши колонки, по усилению
      усилителя, мощности и сопротивлению колонки и типу корпуса, и применяет их к выбранным
      выходам (см. <em>Лимитер</em> ниже).
    </dd>
    <dt>☰ Presets</dt>
    <dd>Загрузка и сохранение пресетов DSP (см. <em>Пресеты</em>).</dd>
    <dt>⚙ Settings</dt>
    <dd>
      Частота обновления индикаторов, параметры отображения, кто подключён, устройство (см.
      <em>Настройки</em>).
    </dd>
    <dt>❓ Help</dt>
    <dd>Эта страница.</dd>
  </dl>
</section>

<section id="help-channels">
  <h2>Выбор отображаемых каналов</h2>
  <p>
    В Live, Params и All-in-one над каналами есть ряд кнопок: <strong>All</strong> (все),
    <strong>In</strong> (только входы), <strong>Out</strong> (только выходы), затем по кнопке на
    канал (A–D для входов, 1–8 для выходов, с их названиями). Подсвеченная кнопка означает, что
    канал показан; нажмите на канал, чтобы показать или скрыть его.
  </p>
  <ul>
    <li>
      Каждый вид запоминает свой выбор на этом устройстве (Params: один выбор для всех его
      настроек).
    </li>
    <li>
      У каждого канала свой цвет, одинаковый везде. Связанные каналы имеют общий цвет своей
      группы.
    </li>
    <li>
      С опцией <em>Merge linked channels</em> (Settings) группа связанных каналов показывается
      как один канал, например «Out 1+5».
    </li>
    <li>Полоса с надписью <em>IN | OUT</em> отделяет входы от выходов.</li>
  </ul>
</section>

<section id="help-controls">
  <h2>Фейдеры, поля и кнопки</h2>
  <dl>
    <dt>Фейдеры</dt>
    <dd>
      Фейдер двигается, только если перетаскивание <strong>начато с его ручки</strong>, поэтому
      прокрутка страницы никогда не сдвинет его случайно. − и + меняют значение на один шаг;
      удерживайте их для повтора. Нажмите на значение над фейдером, чтобы ввести число.
    </dd>
    <dt>Числовые поля</dt>
    <dd>
      − / + меняют значение на один шаг DSP (удерживайте для повтора); ползунок под ними меняет
      его быстро; нажмите на число, чтобы ввести его. Значения всегда округляются до того, что
      DSP может сохранить.
    </dd>
    <dt>Кнопки On / Off</dt>
    <dd>Подсвечено (зелёным) — включено. MUTE и Bypass подсвечиваются красным, когда активны.</dd>
    <dt>Разделы</dt>
    <dd>Нажмите на заголовок раздела (со стрелкой ›), чтобы свернуть или развернуть его.</dd>
    <dt>График эквалайзера</dt>
    <dd>
      У каждой полосы эквалайзера есть пронумерованная точка на графике частотной
      характеристики: тяните её вбок, чтобы изменить частоту, и вверх / вниз — усиление; с
      мышью крутите колёсико над ней, чтобы изменить добротность Q. Серые точки — полосы без
      эффекта (выключенные или на 0 дБ).
    </dd>
    <dt>Метки</dt>
    <dd>
      Настройка с меткой «unverified» ещё не проверена на настоящем DSP 408; на настоящем DSP её
      можно изменить, только если сервер запущен с <code>--experimental</code>.
    </dd>
  </dl>
</section>

<section id="help-together">
  <h2>Совместная работа</h2>
  <p>
    По умолчанию каждый может менять всё; действует последнее изменение, и все сразу его видят.
  </p>
  <dl>
    <dt>✋ Take control</dt>
    <dd>
      Пока управление у вас, остальные устройства в режиме «только чтение» (они показывают, у
      кого управление). Нажмите <em>Release control</em>, когда закончите. Управление
      освобождается само после некоторого времени без ваших действий (панель показывает
      оставшееся время).
    </dd>
    <dt>🔒 Lock screen</dt>
    <dd>
      Переводит <strong>это</strong> устройство в режим «только чтение» — для телефона или
      компьютера, оставленного без присмотра: всё остаётся видимым (включая индикаторы) и вид не
      меняется, но ничего нельзя изменить или переключить. <em>Unlock screen</em> запрашивает код
      доступа. Блокировка сохраняется после перезагрузки страницы.
    </dd>
    <dt>Мастер (Settings)</dt>
    <dd>
      Один человек может стать мастером кнопкой <em>Become master</em> в <em>Settings › Connected
      clients</em>. Мастер может отключить другого клиента кнопкой <em>Disconnect</em> (тот
      возвращается на экран входа и должен снова ввести код доступа) и запретить новые
      подключения переключателем <em>Block new connections</em>: войти больше никто не сможет, а
      уже подключённые браузеры останутся на связи. Запрет снимается, когда мастер нажимает
      <em>Stop being master</em>, выходит из системы или не открывал приложение 5 минут. Чтобы
      исключить кого-то: отключите его, затем включите запрет.
    </dd>
  </dl>
</section>

<section id="help-presets">
  <h2>Пресеты</h2>
  <p>
    Пресет — это полная конфигурация (все настройки всех каналов), хранящаяся в самом DSP. DSP
    хранит 20 пресетов (U01–U20) и заводские настройки (F00).
  </p>
  <dl>
    <dt>Recall</dt>
    <dd>
      Загружает пресет: <strong>все текущие настройки заменяются</strong>. Если в текущей
      конфигурации есть несохранённые изменения, они теряются (приложение спрашивает заранее).
      Это занимает несколько секунд.
    </dd>
    <dt>Store</dt>
    <dd>
      Сохраняет текущую конфигурацию в ячейку пресета с названием (не более 14 простых
      символов). Прежнее содержимое ячейки перезаписывается. F00 перезаписать нельзя.
    </dd>
    <dt>Несохранённые изменения</dt>
    <dd>
      Обозначаются оранжевой точкой на боковой панели и надписью «● unsaved changes» на этой
      странице, с кнопкой <em>Save to Uxx</em>, чтобы сохранить их в текущий пресет.
    </dd>
    <dt>Export / Import .prs</dt>
    <dd>
      Файлы пресетов официального редактора t.racks. <em>Export live setup</em> сохраняет текущую
      конфигурацию в файл. <em>Import .prs…</em> загружает файл в DSP (<strong>все текущие настройки
      заменяются</strong>; на время загрузки выходы заглушаются) и может сразу сохранить его в
      ячейку. Уровни матрицы и обход PEQ в этих файлах не хранятся.
    </dd>
  </dl>
</section>

<section id="help-settings">
  <h2>Настройки</h2>
  <dl>
    <dt>Meters · Refresh rate</dt>
    <dd>
      Как часто обновляются индикаторы уровня (от 1 до 10 раз в секунду). Действует на все
      подключённые устройства.
    </dd>
    <dt>Meters · Scale bottom / top</dt>
    <dd>
      Диапазон всех индикаторов уровня, по умолчанию от −40 до +20 dBu (+20 dBu — максимум DSP).
      Уровни, CLIP и цвета не меняются. Только на этом устройстве.
    </dd>
    <dt>Display · Merge linked channels</dt>
    <dd>
      Показывает каждую группу связанных каналов как один канал во всех видах (кроме Params ›
      Matrix и Link). Изменение применяется ко всей группе; названия и маршрутизация остаются
      для каждого канала. Только на этом устройстве.
    </dd>
    <dt>Display · Signal indicator (SIG)</dt>
    <dd>
      Уровень, выше которого загорается SIG (по умолчанию −60 dBu). Неподключённый вход
      показывает около −86 dBu. Только на этом устройстве.
    </dd>
    <dt>Connected clients</dt>
    <dd>Все, кто сейчас пользуется приложением, и у кого управление.</dd>
    <dt>Device</dt>
    <dd>
      Состояние, модель и прошивка DSP, версия приложения. <em>Refresh from device</em> заново
      считывает все настройки из DSP. <em>Disconnect from DSP and shutdown</em> корректно
      останавливает сервер: он отключается от DSP (который принимает только одну программу
      одновременно, например, чтобы открыть редактор t.racks), затем останавливает приложение для
      всех. DSP сохраняет свои настройки. Недоступно, пока управление или роль мастера у
      кого-то другого.
    </dd>
    <dt>This browser</dt>
    <dd>
      <em>Log out</em> выходит из приложения только на этом устройстве; сервер продолжает работать.
    </dd>
  </dl>
</section>

<section id="help-audio">
  <h2>Звуковые настройки: пояснения</h2>
  <p>
    Каждый <strong>вход</strong> (A–D) — это входящий сигнал; каждый <strong>выход</strong> (1–8)
    питает усилитель. DSP обрабатывает входы, направляет их на выходы (маршрутизация) и затем
    обрабатывает каждый выход.
  </p>
  <dl>
    <dt>Уровни и индикаторы (dBu)</dt>
    <dd>
      Уровни указаны в dBu. Индикаторы доходят до +20 dBu — максимума DSP:
      <strong>CLIP</strong> загорается, когда сигнал его достигает и искажается. Цвета: зелёный
      до 0 dBu, жёлтый до +6, оранжевый до +12, красный выше. Уровень становится оранжевым,
      когда работает компрессор, тёмно-оранжевым — когда работает лимитер, красным — при
      перегрузке. <strong>SIG</strong> горит, пока в канале есть сигнал (выше −60 dBu,
      настраивается в Settings).
    </dd>
    <dt>Gain (усиление)</dt>
    <dd>Громкость канала в дБ (от −60 до +12). 0 дБ оставляет уровень без изменений.</dd>
    <dt>Mute</dt>
    <dd>Отключает звук канала (его настройки сохраняются).</dd>
    <dt>Phase (Ø)</dt>
    <dd>
      Инвертирует полярность сигнала. Полезно, когда две колонки (например, сабвуфер и сателлит)
      гасят друг друга около частоты раздела: попробуйте и оставьте вариант, который звучит
      полнее.
    </dd>
    <dt>Delay (задержка)</dt>
    <dd>
      Задерживает сигнал; задаётся в миллисекундах или в метрах (расстояние, которое звук
      проходит за это время). Нужна, чтобы выровнять колонки, стоящие на разном расстоянии от
      слушателей, чтобы их звук приходил одновременно.
    </dd>
    <dt>Фильтры (ФВЧ / ФНЧ)</dt>
    <dd>
      Фильтр <strong>высоких частот</strong> (high-pass) убирает всё ниже своей частоты
      (например, низы, идущие на маленький сателлит); фильтр <strong>низких частот</strong>
      (low-pass) убирает всё выше (например, верха, идущие на сабвуфер). Вместе они делят звук
      между колонками (кроссовер). Крутизна (slope) показывает, насколько резко идёт срез (от 6
      до 48 дБ на октаву), и его тип: BW (Баттерворт), BL (Бессель) или LR (Линквиц–Райли,
      обычный выбор для сопряжения двух колонок). <em>Off</em> выключает фильтр.
    </dd>
    <dt>EQ (параметрический эквалайзер)</dt>
    <dd>
      До 8 полос на входах и 9 на выходах, каждая поднимает или ослабляет диапазон частот. У
      полосы есть <strong>тип</strong> (Peak: колокол вокруг своей частоты; Low / High Shelf:
      всё ниже / выше; LP / HP: ФНЧ / ФВЧ; Allpass: меняет только фазу),
      <strong>частота</strong>, <strong>усиление</strong> (+ поднимает, − ослабляет) и
      <strong>добротность Q</strong> (ширина: высокая Q — узкая полоса, низкая Q — широкая).
      Каждую полосу можно выключить, а <em>Bypass</em> отключает весь эквалайзер.
    </dd>
    <dt>GEQ (графический эквалайзер)</dt>
    <dd>На входах: 31 фиксированная полоса, по одной на треть октавы, у каждой своё усиление.</dd>
    <dt>Компрессор</dt>
    <dd>
      На выходах. Выше своего <strong>порога</strong> (threshold) он снижает уровень согласно
      <strong>степени сжатия</strong> (ratio) (например, 1:4: на 4 дБ больше на входе дают на 1
      дБ больше на выходе; <em>Limit</em> — самое сильное сжатие). <strong>Attack</strong> —
      скорость срабатывания, <strong>release</strong> — скорость восстановления,
      <strong>knee</strong> — плавность начала сжатия. CMP горит, пока он работает.
    </dd>
    <dt>Лимитер</dt>
    <dd>
      На выходах: потолок, выше которого уровень выхода не поднимается, для защиты усилителей и
      колонок. LIM горит, пока он работает; если горит постоянно, система перегружена. Вкладка
      <em>Limiter calc</em> рассчитывает безопасный порог для ваших колонок.
    </dd>
    <dt>Noise gate (шумоподавитель)</dt>
    <dd>
      На входах: закрывает (заглушает) канал, пока его уровень ниже порога, например чтобы
      убрать фоновый шум микрофона между фразами. Attack, hold и release задают, как быстро он
      открывается, как долго остаётся открытым и как быстро закрывается.
    </dd>
    <dt>Matrix (маршрутизация)</dt>
    <dd>
      Какие входы питают каждый выход. Нажмите на клетку, чтобы подключить или отключить вход от
      выхода.
    </dd>
    <dt>Link (связь)</dt>
    <dd>
      Связанные каналы меняются вместе: изменение одного применяется ко всем (усиление, mute,
      эквалайзер, фильтры, динамика, задержка…), кроме названий и маршрутизации. При связывании
      первый канал (с наименьшим номером) становится ведущим: его настройки копируются на
      остальные. Используется для стереопар (например, левый и правый сабвуферы). Под каналами
      раздел <em>Channel names</em> позволяет сразу переименовать каждый из них.
    </dd>
  </dl>
</section>

